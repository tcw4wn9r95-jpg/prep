#!/usr/bin/env node
'use strict';

/**
 * Regenerates the table in docs/n-rule-evidence.md.
 *
 * The trigger set in lib/nrule.js is a claim about Luxembourgish, and the
 * project rule is that we do not make those from memory. This script derives
 * it from LOD's 59,019 example sentences so the claim can be re-checked
 * against every future release of the data.
 *
 *   node pipeline/test/nrule-evidence.js [--write]
 */

const fsp = require('node:fs/promises');
const path = require('node:path');

const paths = require('../lib/paths');
const xml = require('../lib/xml');
const { tokenise } = require('../lib/lux-text');

async function measure() {
  const after = new Map(); // first letter of word2 -> { withN, total }
  let pairs = 0;
  let nFinal = 0;

  for await (const record of xml.records(paths.datasetXmlPath('search'), 'entry')) {
    for (const example of xml.findAll(record, 'example')) {
      const text = xml.find(example, 'text')?.text;
      if (!text) continue;
      const tokens = tokenise(text);
      for (let i = 0; i + 1 < tokens.length; i += 1) {
        const a = tokens[i];
        const b = tokens[i + 1];
        if (a.isClitic) continue;
        if (!/^[\p{L}][\p{L}-]*$/u.test(a.value)) continue;
        const first = (b.clitic ? b.clitic : b.value)[0];
        if (!first || !/\p{L}/u.test(first)) continue;
        const key = first.toLowerCase();
        pairs += 1;
        const bucket = after.get(key) ?? { withN: 0, total: 0 };
        bucket.total += 1;
        if (a.value.toLowerCase().endsWith('n')) {
          bucket.withN += 1;
          nFinal += 1;
        }
        after.set(key, bucket);
      }
    }
  }

  const rows = [...after.entries()]
    .filter(([, bucket]) => bucket.total >= 200)
    .map(([letter, bucket]) => ({ letter, ...bucket, share: bucket.withN / bucket.total }))
    .sort((a, b) => b.share - a.share);

  return { rows, pairs, nFinal };
}

function render({ rows, pairs, nFinal }) {
  const lines = [];
  lines.push('# Evidence for the n-rule trigger set');
  lines.push('');
  lines.push('Generated by `node pipeline/test/nrule-evidence.js --write`. Do not edit by hand.');
  lines.push('');
  lines.push(
    'The Eifeler Regel drops a word-final `n` unless the next sound is one of a small set. ' +
      '`pipeline/lib/nrule.js` hard-codes that set, so this table exists to show it was measured ' +
      "rather than recalled - and to make a future LOD release able to contradict it.",
  );
  lines.push('');
  lines.push('## Method');
  lines.push('');
  lines.push(
    'Take every adjacent word pair in the `<text>` example sentences of the LOD search index. ' +
      'Group by the first letter of the second word, and measure what share of those pairs have a ' +
      'first word ending in `-n`. Where the rule keeps the `n`, that share is high; where the rule ' +
      'drops it, only the words whose `n` is stem-final survive, so the share collapses.',
  );
  lines.push('');
  lines.push(`Corpus: ${pairs.toLocaleString()} adjacent pairs, ${nFinal.toLocaleString()} with an \`-n\` first word.`);
  lines.push('');
  lines.push('## Result');
  lines.push('');
  lines.push('| next word starts with | pairs | first word ends in -n | share |');
  lines.push('| --- | ---: | ---: | ---: |');
  for (const row of rows) {
    lines.push(
      `| \`${row.letter}\` | ${row.total.toLocaleString()} | ${row.withN.toLocaleString()} | ${(100 * row.share).toFixed(1)}% |`,
    );
  }
  lines.push('');

  const high = rows.filter((row) => row.share >= 0.15).map((row) => row.letter);
  const low = rows.filter((row) => row.share < 0.15).map((row) => row.letter);
  lines.push(
    `The split is clean, with no letter in between: **${high.join(', ')}** keep the \`n\`, ` +
      `**${low.join(', ')}** drop it. That is \`n d t z h\` plus the vowels, which is the set ` +
      '`TRIGGER_CONSONANTS` and `VOWELS` encode.',
  );
  lines.push('');
  lines.push('## What this table does not settle');
  lines.push('');
  lines.push(
    '- **Pronunciation, not spelling, drives the rule.** Numerals (`20` = *zwanzeg*), initialisms ' +
      '(`CV` = */tseːveː/*) and single letters are read aloud, so their written first character ' +
      'predicts nothing. `hasOpaqueOnset` skips them.',
  );
  lines.push(
    '- **LOD is not internally consistent.** Before `sech`, `se` and the `sen-` possessives it ' +
      'writes both forms. `build-corpus.js` measures that variation and downgrades those contexts ' +
      'to warnings; the table lands in `content/lexicon.json` under `nRuleRetentionExceptions`.',
  );
  lines.push(
    '- **Homographs break the reverse direction.** `A` the noun looks like `a`, the dropped form of ' +
      '`an`; `Wee` looks like `wee(n)`. Flagging a *missing* `n` therefore only ever warns.',
  );
  lines.push('');
  lines.push('Run `node pipeline/test/calibrate.js` for what all of that costs on LOD\'s own sentences.');
  lines.push('');
  return lines.join('\n');
}

async function main() {
  const result = await measure();
  const markdown = render(result);
  if (process.argv.includes('--write')) {
    const file = path.join(paths.ROOT, 'docs', 'n-rule-evidence.md');
    await fsp.mkdir(path.dirname(file), { recursive: true });
    await fsp.writeFile(file, markdown);
    process.stdout.write(`Wrote ${path.relative(paths.ROOT, file)}\n`);
  } else {
    process.stdout.write(markdown);
  }
}

if (require.main === module) {
  main().catch((error) => {
    process.stderr.write(`nrule-evidence failed: ${error.stack}\n`);
    process.exit(1);
  });
}

module.exports = { measure };
